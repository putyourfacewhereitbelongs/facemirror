/**
 * smoothing.js — One-Euro filters, critically-damped springs, fixed-timestep
 * accumulation, and binary hysteresis. Pure math: no DOM, no THREE (§9.1).
 *
 * Why fixed-timestep: One-Euro assumes uniform dt; feeding it wall-clock dt
 * makes cutoffs drift with frame time (trap §11.12 sibling — GC pauses look
 * like face stutter). All filters run at CONFIG.rateHz substeps instead.
 */

/** @type {Record<string, number>} */
export const CONFIG = {
  rateHz: 60,           // fixed solver rate; substeps come from the accumulator
  maxSubsteps: 4,       // clamp so a tab-wake does not fast-forward the face
  dcutoffDefault: 1.0,  // One-Euro derivative cutoff (Hz)
  betaDefault: 0.01,    // One-Euro speed coefficient
  hysteresisBand: 0.10, // ±10% band on every binary threshold (§5.4)
};

/**
 * Per-channel-group One-Euro cutoffs (Hz) and beta, per spec §5.4.
 * `eyeBlink*` is absent on purpose: blinks are generated by the blink
 * scheduler curve and must never be smoothed (trap §11.4).
 * @type {Record<string, {fcMin: number, beta: number}>}
 */
export const GROUP_FILTERS = {
  mouth:     { fcMin: 3.0, beta: CONFIG.betaDefault },
  lips:      { fcMin: 3.0, beta: CONFIG.betaDefault },
  brows:     { fcMin: 1.0, beta: CONFIG.betaDefault },
  cheeks:    { fcMin: 1.5, beta: CONFIG.betaDefault },
  jaw:       { fcMin: 6.0, beta: CONFIG.betaDefault },
  eyes:      { fcMin: 4.0, beta: CONFIG.betaDefault },
  nose:      { fcMin: 2.0, beta: CONFIG.betaDefault },
  tongue:    { fcMin: 4.0, beta: CONFIG.betaDefault },
  look:      { fcMin: 8.0, beta: CONFIG.betaDefault },
  pose:      { fcMin: 5.0, beta: CONFIG.betaDefault },
};

/** Default filter params for channels with no explicit group. */
export const DEFAULT_FILTER = { fcMin: 2.0, beta: CONFIG.betaDefault };

/**
 * Exponential smoothing of a cutoff frequency against sampling rate.
 * (One-Euro paper, §3 "Filtering": α = 1 / (1 + τ/dt), τ = 1/(2π·fc).)
 * @param {number} cutoffHz cutoff frequency in Hz
 * @param {number} dtSec sampling period in seconds
 * @returns {number} smoothing factor in (0, 1)
 */
export function alphaFor(cutoffHz, dtSec) {
  const r = 2 * Math.PI * cutoffHz * dtSec;
  return r / (r + 1);
}

/**
 * One-Euro filter for a scalar signal (Casiez et al. 2012).
 * Low jitter at rest, low lag on motion: cutoff rises with signal speed.
 */
export class OneEuro {
  /**
   * @param {number} [fcMin] minimum cutoff (Hz) at rest
   * @param {number} [beta] speed coefficient (Hz per unit/s)
   * @param {number} [dcutoff] derivative cutoff (Hz)
   */
  constructor(fcMin = 1.0, beta = CONFIG.betaDefault, dcutoff = CONFIG.dcutoffDefault) {
    this.fcMin = fcMin;
    this.beta = beta;
    this.dcutoff = dcutoff;
    this.xPrev = /** @type {number|null} */ (null);
    this.dxPrev = 0;
  }

  /** Reset to un-initialized state. */
  reset() {
    this.xPrev = null;
    this.dxPrev = 0;
  }

  /**
   * Filter one sample.
   * @param {number} x raw sample
   * @param {number} dtSec seconds since previous sample (uniform when run
   *   through a FixedStepper; never 0)
   * @returns {number} smoothed sample
   */
  filter(x, dtSec) {
    const dt = dtSec > 1e-6 ? dtSec : 1 / CONFIG.rateHz;
    if (this.xPrev === null) {
      this.xPrev = x;
      this.dxPrev = 0;
      return x;
    }
    // Derivative of the raw signal, low-passed at dcutoff.
    const dxRaw = (x - this.xPrev) / dt;
    const aD = alphaFor(this.dcutoff, dt);
    const dx = aD * dxRaw + (1 - aD) * this.dxPrev;
    // Cutoff adapts to speed: fc = fcMin + beta·|dx|
    const fc = this.fcMin + this.beta * Math.abs(dx);
    const a = alphaFor(fc, dt);
    const out = a * x + (1 - a) * this.xPrev;
    this.xPrev = out;
    this.dxPrev = dx;
    return out;
  }
}

/**
 * Critically-damped (ζ=1) second-order spring toward a target.
 * Stable for any dt via implicit exponential integration (no overshoot,
 * no ringing even if dt spikes — important on a 4 GB tab).
 */
export class DampedSpring {
  /**
   * @param {number} [omega] natural frequency (rad/s); §5.4 uses ω≈18 for
   *   head follow, ω=2.5 ζ=0.7 for emotion transitions
   * @param {number} [zeta] damping ratio (1 = critical)
   */
  constructor(omega = 18, zeta = 1) {
    this.omega = omega;
    this.zeta = zeta;
    this.value = 0;
    this.velocity = 0;
  }

  /** @param {number} v snap state (used on teleports/undo) */
  reset(v = 0) {
    this.value = v;
    this.velocity = 0;
  }

  /**
   * Advance one substep.
   * @param {number} target desired value
   * @param {number} dtSec substep seconds
   * @returns {number} new value
   */
  step(target, dtSec) {
    const dt = dtSec > 1e-6 ? dtSec : 1 / CONFIG.rateHz;
    // Implicit-exponential integrator for x'' + 2ζω x' + ω²(x−t) = 0.
    const w = this.omega;
    const z = this.zeta;
    const decay = Math.exp(-z * w * dt);
    const err = this.value - target;
    if (z >= 1) {
      // Critical/over-damped closed form (no trig → cannot ring).
      const b = this.velocity + w * err;
      this.value = target + (err + b * dt) * decay;
      this.velocity = (this.velocity - w * b * dt) * decay;
    } else {
      // Under-damped closed form (emotion transitions want the 8% overshoot).
      // x = t + e^{-ζωt}·(err·cos ωd t + ((v0+ζω·err)/ωd)·sin ωd t)
      const wd = w * Math.sqrt(1 - z * z);
      const s = Math.sin(wd * dt);
      const c = Math.cos(wd * dt);
      const e = decay;
      const k = (this.velocity + z * w * err) / wd;
      this.value = target + e * (err * c + k * s);
      this.velocity = e * (this.velocity * c - ((w * w * err + z * w * this.velocity) / wd) * s);
    }
    return this.value;
  }
}

/**
 * Fixed-rate timestep accumulator. Returns whole substeps of 1/CONFIG.rateHz
 * so every filter sees uniform dt (§5.4).
 */
export class FixedStepper {
  /** @param {number} [rateHz] solver rate */
  constructor(rateHz = CONFIG.rateHz) {
    this.rateHz = rateHz;
    this.stepSec = 1 / rateHz;
    this.acc = 0;
  }

  /**
   * Feed wall-clock frame time.
   * @param {number} dtSec frame delta seconds (clamped to 250 ms)
   * @returns {number} number of substeps to run now (0..CONFIG.maxSubsteps)
   */
  advance(dtSec) {
    this.acc += Math.min(Math.max(dtSec, 0), 0.25);
    let n = 0;
    while (this.acc >= this.stepSec && n < CONFIG.maxSubsteps) {
      this.acc -= this.stepSec;
      n++;
    }
    // Drop excess time instead of fast-forwarding after a stall.
    if (this.acc > this.stepSec * CONFIG.maxSubsteps) this.acc = 0;
    return n;
  }
}

/**
 * Binary threshold with a ±hysteresis band (§5.4: every binary gets one).
 * @param {number} value current signal in [0,1]
 * @param {boolean} state previous latched state
 * @param {number} threshold trigger level
 * @param {number} [band] band half-width (default CONFIG.hysteresisBand)
 * @returns {boolean} new latched state
 */
export function hysteretic(value, state, threshold, band = CONFIG.hysteresisBand) {
  if (state) return value > threshold - band;
  return value > threshold + band * 0; // trigger edge at threshold; release is threshold-band
}

/**
 * Hysteresis helper with explicit on/off levels (on = threshold+band*0,
 * off = threshold−band). Returns {state, justChanged}.
 * @param {number} value
 * @param {boolean} state
 * @param {number} threshold
 * @param {number} [band]
 * @returns {{state: boolean, changed: boolean}}
 */
export function hystereticEx(value, state, threshold, band = CONFIG.hysteresisBand) {
  const on = threshold;
  const off = threshold - band;
  let next = state;
  if (!state && value >= on) next = true;
  else if (state && value <= off) next = false;
  return { state: next, changed: next !== state };
}

/**
 * Per-channel One-Euro bank for the 52 weights. Skips eyeBlink channels —
 * the blink scheduler owns those curves (trap §11.4).
 */
export class ChannelFilterBank {
  /**
   * @param {string[]} channelNames ordered ARKit names (index = channel id)
   * @param {Record<string, string>} [groupOf] name → group key
   */
  constructor(channelNames, groupOf = {}) {
    this.n = channelNames.length;
    this.betaScale = 1;
    this.filters = channelNames.map((name) => {
      if (name === 'eyeBlinkLeft' || name === 'eyeBlinkRight') return null;
      const g = GROUP_FILTERS[groupOf[name] ?? 'mouth'] ?? DEFAULT_FILTER;
      const f = new OneEuro(g.fcMin, g.beta, CONFIG.dcutoffDefault);
      f.baseBeta = f.beta;
      return f;
    });
  }

  /**
   * UI "Responsiveness" slider (§10): scales every filter's β
   * (0.002–0.05 band).
   * @param {number} scale multiplier around 1
   */
  setBetaScale(scale) {
    this.betaScale = scale;
    for (const f of this.filters) {
      if (f) f.beta = Math.min(Math.max(f.baseBeta * scale, 0.002), 0.05);
    }
  }

  /** Reset all filters (mode switches, calibration done). */
  reset() {
    for (const f of this.filters) f?.reset();
  }

  /**
   * Smooth every channel in place.
   * @param {Float32Array} out preallocated output (trap §11.12: no new arrays)
   * @param {Float32Array} raw input weights
   * @param {number} dtSec uniform substep seconds
   */
  apply(out, raw, dtSec) {
    for (let i = 0; i < this.n; i++) {
      const f = this.filters[i];
      out[i] = f ? f.filter(raw[i], dtSec) : raw[i];
    }
  }
}
